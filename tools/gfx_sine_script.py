#!/usr/bin/env python3
"""Write the protocol lines for axes plus a sine curve, as the HP-41 test
program sends them: FIX 4 numbers, one or two commands per line, at most 24
characters per line (the ALPHA register). Output is a hp41-gfx --script file.
usage: gfx_sine_script.py [steps] > tests/gfx/sine.gfx
"""
import math, sys

def fix4(v):
    # HP-41 FIX 4 with flag 29 clear: no digit grouping. -0.0000 shows as 0.0000.
    s = "%.4f" % v
    return "0.0000" if s == "-0.0000" else s

steps = int(sys.argv[1]) if len(sys.argv) > 1 else 63
lines = ["GI:C 0", "SC -7 7 -1.2 1.2", "K 1:M -7 0:D 7 0", "K 1:M 0 -1.2:D 0 1.2", "K 2"]
pts = [(-6.3 + 12.6 * i / steps) for i in range(steps + 1)]
cmds = ["M %s %s" % (fix4(pts[0]), fix4(math.sin(pts[0])))]
cmds += ["D %s %s" % (fix4(x), fix4(math.sin(x))) for x in pts[1:]]
cur = ""
for c in cmds:
    if not cur:
        cur = c
    elif len(cur) + 1 + len(c) <= 24:
        cur += ":" + c
    else:
        lines.append(cur); cur = c
if cur:
    lines.append(cur)
print("# axes and sine curve, %d segments, generated by tools/gfx_sine_script.py" % steps)
for l in lines:
    assert len(l) <= 24, l
    print(l)
print("!err 0")
