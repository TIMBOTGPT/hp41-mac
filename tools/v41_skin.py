#!/usr/bin/env python3
"""Build a local skin from V41's own photographic keyboard bitmap.

Reads XLarge.bmp and the key rectangles in HP41Keyboard.cpp from an upstream
V41 source tree and writes skin/local/v41.png and skin/local/v41.layout.
The output is derived from V41's artwork, is for local use, and is ignored
by git.

usage: v41_skin.py [path-to-V41R9/V41]
"""
import os, re, sys
from PIL import Image
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/Projects/hp41-upstream/v41r9o/src/V41R9/V41')
out = os.path.join(here, '..', 'skin', 'local')
os.makedirs(out, exist_ok=True)
text = open(os.path.join(src, 'HP41Keyboard.cpp'), encoding='latin-1').read()

def rects(name):
    body = re.search(r'RECT\s+' + name + r'\[\]\s*=\s*\{(.*?)\};', text, re.S).group(1)
    return [tuple(map(int, m)) for m in re.findall(r'\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}', body)]
def rect(name):
    return tuple(map(int, re.search(r'RECT\s+' + name + r'\s*=\s*\{(\d+),(\d+),(\d+),(\d+)\}', text).groups()))

R = rects('RectKeyboardXLarge')
codes = [0x18, 0xc6, 0xc5, 0xc4,
         0x10, 0x30, 0x70, 0x80, 0xc0,
         0x11, 0x31, 0x71, 0x81, 0xc1,
         0x12, 0x32, 0x72, 0x82, 0xc2,
         0x13, 0x73, 0x83, 0xc3,
         0x14, 0x34, 0x74, 0x84,
         0x15, 0x35, 0x75, 0x85,
         0x16, 0x36, 0x76, 0x86,
         0x17, 0x37, 0x77, 0x87]
lcd = rect('RectLCDXLarge'); ann = rect('RectAnnunXLarge')
img = Image.open(os.path.join(src, 'XLarge.bmp')).convert('RGB')
img.save(os.path.join(out, 'v41.png'))
W, H = img.size
# LCD background colour sampled from the bitmap, between the character row and the annunciators
bg = img.getpixel(((lcd[0] + lcd[2]) // 2, lcd[3] + 1))
with open(os.path.join(out, 'v41.layout'), 'w') as f:
    f.write('# generated by tools/v41_skin.py from V41 XLarge.bmp\n')
    f.write(f'face {W} {H}\n')
    f.write('lcd %d %d %d %d\n' % (lcd[0], lcd[1], lcd[2] - lcd[0], ann[3] - lcd[1]))
    f.write('cells %d %d %d %d\n' % (lcd[0] + 6, lcd[1] + 3, lcd[2] - lcd[0] - 12, lcd[3] - lcd[1] - 6))
    f.write('lcdcolors %02x%02x%02x 1d241c\n' % bg)
    f.write('annrow %d %d %d %d\n' % (ann[0], ann[1], ann[2] - ann[0], ann[3] - ann[1]))
    for c, r in zip(codes, R):
        f.write('key %02x %d %d %d %d\n' % (c, r[0], r[1], r[2] - r[0], r[3] - r[1]))
print('wrote', os.path.join(out, 'v41.png'), W, H, 'lcd bg', bg)
